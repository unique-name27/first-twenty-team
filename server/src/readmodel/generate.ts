// Writes the read model (spec.ts) as one migration body: the guarded cast helpers, every view, and the
// read-only login's grant. `npm run server:gen-sql -- --read-model` prints it; --write saves it as the next
// numbered migration and --replace rewrites the newest read-model migration (it refuses one on main).
// readmodel.test.ts checks that the newest NNN_read_model.sql equals readModelSql() exactly.
import { readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { type Column, lit, table } from './columns'
import { VIEW_PRIVILEGES_SQL } from './privileges'
import { READ_MODEL, RETIRED_VIEWS } from './spec'
import type { View } from './views'

/** Read-model migrations: 007_read_model.sql, and each later NNN_read_model.sql that replaced it. */
export const READ_MODEL_FILE_RE = /^(\d{3})_read_model\.sql$/

/** The command that brings the read model's migration up to date (named in the drift test's failure). */
export const READ_MODEL_COMMAND = 'npm run server:gen-sql -- --read-model --write'

const HEADER = `-- The read model (docs/DEV.md, "Query the data with SQL"; ready-made queries in server/deploy/browse.sql):
-- typed views over the JSONB records, so the data reads with plain SQL. One view per core record
-- collection (v_people, v_comp, v_jobs, ...), list views (v_checklist_tasks, v_application_stages,
-- v_pay_runs), journeys across them (v_current_job, v_hire_journey, v_pipeline_funnel,
-- v_headcount_by_month) and v_integrity_problems, the checks of src/domain/integrity.ts as rows.
--
-- Generated by \`npm run server:gen-sql -- --read-model\` from server/src/readmodel/spec.ts and the checks
-- in src/domain/integrity.ts; never edit it by hand. A later change to either ships as a new migration
-- whose body is the generator's whole output: \`${READ_MODEL_COMMAND}\`
-- saves it as the next number. It drops every read-model view and creates them all again, so an applied
-- migration never changes. readmodel.test.ts fails while the newest NNN_read_model.sql differs from the
-- generator.
--
-- Every view: workspace_id first (filter on it to read one company); security_invoker, so a login reads
-- through a view only what it may read in the tables (needs Postgres 15 or newer); reads only the record
-- tables, workspace_docs and workspaces, never users, sessions, trusted_devices or invites; plain views,
-- no triggers, nothing on the write path (no role keeps a write right on them). The server's own role
-- reads them through its default privileges (server/deploy/postgres-setup.sql); the read-only login gets
-- them at the end of this file when it exists, and from server/deploy/viewer-role.sql.`

/** The oldest Postgres the read model runs on (security_invoker views), as server_version_num counts it. */
const MIN_SERVER_VERSION_NUM = 150000

const VERSION_GUARD = `-- Postgres 15 or newer first: the views read with the reader's own rights (security_invoker), which older
-- versions refuse. Stopping here leaves the database as it was.
DO $$
BEGIN
  IF current_setting('server_version_num')::int < ${MIN_SERVER_VERSION_NUM} THEN
    RAISE EXCEPTION 'First Twenty needs Postgres 15 or newer (this server runs %). docs/SERVER.md, "Before you start", says how to get it.', current_setting('server_version');
  END IF;
END
$$;`

// The function bodies name ft_as_date with its schema: Postgres reads a SQL function's body with the
// session's search_path when it runs it, and a SQL client may have set one without public.
const FUNCTIONS = `-- Guarded casts: text that is not a value of the type gives NULL instead of failing the whole query
-- (an empty string, junk, a day such as Feb 30, a time zone offset past 15:59). Dates must be 'YYYY-MM-DD'
-- (src/domain/paths.ts asDate agrees), timestamps full ISO with a zone, numbers JSON numbers.
CREATE OR REPLACE FUNCTION ft_as_date(v text) RETURNS date
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN v ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
    CASE WHEN substr(v, 1, 4)::int >= 1
          AND substr(v, 6, 2)::int BETWEEN 1 AND 12
          AND substr(v, 9, 2)::int BETWEEN 1 AND
              CASE WHEN substr(v, 6, 2)::int = 2 THEN
                     CASE WHEN (substr(v, 1, 4)::int % 4 = 0 AND substr(v, 1, 4)::int % 100 <> 0) OR substr(v, 1, 4)::int % 400 = 0 THEN 29 ELSE 28 END
                   WHEN substr(v, 6, 2)::int IN (4, 6, 9, 11) THEN 30
                   ELSE 31 END
      THEN make_date(substr(v, 1, 4)::int, substr(v, 6, 2)::int, substr(v, 9, 2)::int)
    END
  END
$$;

CREATE OR REPLACE FUNCTION ft_as_timestamptz(v text) RETURNS timestamptz
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN v ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9]([.][0-9]{1,6})?)?(Z|[+-](0[0-9]|1[0-5]):?[0-5][0-9])$'
               AND public.ft_as_date(substr(v, 1, 10)) IS NOT NULL
    THEN v::timestamptz END
$$;

CREATE OR REPLACE FUNCTION ft_as_num(v text) RETURNS numeric
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN v ~ '^-?[0-9]{1,30}([.][0-9]{1,30})?([eE][-+]?[0-9]{1,3})?$' THEN v::numeric END
$$;

CREATE OR REPLACE FUNCTION ft_as_int(v text) RETURNS integer
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN v ~ '^-?[0-9]{1,9}([.]0+)?$' THEN v::numeric::integer END
$$;

CREATE OR REPLACE FUNCTION ft_as_bool(v text) RETURNS boolean
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE v WHEN 'true' THEN true WHEN 'false' THEN false END
$$;

-- A list or an object, or an empty one when the value is something else, so reading a malformed record
-- never fails (jsonb_array_elements and jsonb_each refuse other values).
CREATE OR REPLACE FUNCTION ft_array(v jsonb) RETURNS jsonb
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN jsonb_typeof(v) = 'array' THEN v ELSE '[]'::jsonb END
$$;

CREATE OR REPLACE FUNCTION ft_object(v jsonb) RETURNS jsonb
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN jsonb_typeof(v) = 'object' THEN v ELSE '{}'::jsonb END
$$;

-- Today for the views that depend on it (v_current_job, v_headcount_by_month): the date in the setting
-- first_twenty.today when the session sets one (SET first_twenty.today = '2026-12-31' reads them as of
-- that day), else today in Pacific time, the app's own day, whatever time zone the server or session uses.
CREATE OR REPLACE FUNCTION ft_today() RETURNS date
  LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT coalesce(public.ft_as_date(current_setting('first_twenty.today', true)), (now() AT TIME ZONE 'America/Los_Angeles')::date)
$$;`

/** Words a view column must not be named, so every column reads without quotes. */
const RESERVED = new Set(
  'all analyse analyze and any array as asc asymmetric both case cast check collate column constraint create current_catalog current_date current_role current_time current_timestamp current_user default deferrable desc distinct do else end except false fetch for foreign from grant group having in initially intersect into lateral leading limit localtime localtimestamp not null offset on only or order placing primary references returning select session_user some symmetric table then to trailing true union unique user using variadic when where window with'.split(
    ' ',
  ),
)

const IDENT = /^[a-z_][a-z0-9_]*$/

/** The fixed columns each kind of view starts (and for collections, ends) with. */
function fixedColumns(view: View): string[] {
  if (view.kind === 'collection') return ['workspace_id', 'id', 'version', 'updated_at']
  if (view.kind === 'list') return ['workspace_id', view.parentKey, ...(view.itemId ? ['id'] : []), 'ordinal']
  if (view.kind === 'doc list') return ['workspace_id', 'ordinal']
  return []
}

function checkView(view: View, seen: Set<string>): void {
  if (!/^v_[a-z0-9_]+$/.test(view.name)) throw new Error(`View name ${view.name} must be v_ and lowercase`)
  if (seen.has(view.name)) throw new Error(`Two views named ${view.name}`)
  seen.add(view.name)
  if (view.kind === 'sql') return
  const columns = view.kind === 'list' ? [...view.parentColumns, ...view.columns] : view.columns
  const names = [...fixedColumns(view), ...columns.map((c) => c.name)]
  for (const name of names) {
    if (!IDENT.test(name) || RESERVED.has(name)) throw new Error(`${view.name}: column ${name} needs another name`)
  }
  const dup = names.find((n, i) => names.indexOf(n) !== i)
  if (dup) throw new Error(`${view.name}: two columns named ${dup}`)
}

function columnLines(columns: Column[]): string[] {
  return columns.map((c) => `${c.sql} AS ${c.name}`)
}

function selectList(lines: string[]): string {
  return lines.map((l, i) => (i === 0 ? `SELECT ${l}` : `       ${l}`)).join(',\n')
}

function viewBody(view: View): string {
  switch (view.kind) {
    case 'collection':
      return `${selectList(['r.workspace_id', 'r.id', ...columnLines(view.columns), 'r.version', 'r.updated_at'])}
  FROM ${table(view.collection)} r`
    case 'list':
      return `${selectList([
        'r.workspace_id',
        `r.id AS ${view.parentKey}`,
        ...(view.itemId ? [`NULLIF(x.el ->> 'id', '') AS id`] : []),
        'x.n::int AS ordinal',
        ...columnLines(view.parentColumns),
        ...columnLines(view.columns),
      ])}
  FROM ${table(view.collection)} r
 CROSS JOIN LATERAL jsonb_array_elements(ft_array(r.data -> ${lit(view.list)})) WITH ORDINALITY AS x(el, n)`
    case 'doc list':
      return `${selectList(['d.workspace_id', 'x.n::int AS ordinal', ...columnLines(view.columns)])}
  FROM workspace_docs d
 CROSS JOIN LATERAL jsonb_array_elements(ft_array(d.data -> ${lit(view.list)})) WITH ORDINALITY AS x(el, n)
 WHERE d.key = ${lit(view.doc)}`
    case 'sql':
      return view.sql
  }
}

/** The names of every view the read model creates, in creation order. */
export function readModelViews(): string[] {
  return READ_MODEL.map((v) => v.name)
}

/** The whole read model as one migration body. */
export function readModelSql(): string {
  const seen = new Set<string>()
  for (const view of READ_MODEL) checkView(view, seen)
  const names = readModelViews()
  const dropped = [...[...names].reverse(), ...RETIRED_VIEWS.filter((n) => !seen.has(n))]
  const views = READ_MODEL.map(
    (view) => `CREATE VIEW ${view.name} WITH (security_invoker = true) AS
${viewBody(view)};
COMMENT ON VIEW ${view.name} IS ${lit(view.comment)};`,
  )
  const grant = `-- The views only read. Every new relation gets the server role's write rights from its default
-- privileges (server/deploy/postgres-setup.sql), and a simple view would pass writes on to its table, so
-- those rights are taken back here: every role keeps SELECT only. The optional read-only login
-- (server/deploy/viewer-role.sql) gets SELECT when it exists here. npm run server:after-restore runs this
-- again after a restore (server/src/readmodel/privileges.ts).
${VIEW_PRIVILEGES_SQL}`
  return [
    HEADER,
    VERSION_GUARD,
    `-- Views of an earlier read model go first (one statement, so views that read other views go together).\nDROP VIEW IF EXISTS ${dropped.join(', ')};`,
    FUNCTIONS,
    ...views,
    grant,
  ].join('\n\n') + '\n'
}

/** The newest read-model migration in a folder, or null. */
export function newestReadModelFile(dir: string): string | null {
  const files = readdirSync(dir).filter((f) => READ_MODEL_FILE_RE.test(f)).sort()
  return files.at(-1) ?? null
}

/** The next free migration number's file name for a new read model: 008_read_model.sql. */
export function nextReadModelFile(dir: string): string {
  const numbers = readdirSync(dir)
    .map((f) => /^(\d{3})_[a-z0-9_]+\.sql$/.exec(f)?.[1])
    .filter((n): n is string => !!n)
    .map(Number)
  const next = Math.max(0, ...numbers) + 1
  return `${String(next).padStart(3, '0')}_read_model.sql`
}

/** Why a folder's newest read-model migration differs from the generator (the drift test's message), or null. */
export function readModelDrift(dir: string): string | null {
  const newest = newestReadModelFile(dir)
  if (!newest) return `There is no NNN_read_model.sql in server/sql. Run: ${READ_MODEL_COMMAND}`
  if (isCurrent(dir, newest)) return null
  return `server/sql/${newest} differs from what server/src/readmodel/spec.ts and src/domain/integrity.ts generate. Run: ${READ_MODEL_COMMAND} (or --replace when that file is your branch's own and not on main yet)`
}

/** Whether a read-model file says exactly what the generator says now (line endings aside). */
export function isCurrent(dir: string, file: string): boolean {
  return readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n') === readModelSql()
}
